`timescale 1ns/100ps
// -----------------------------------------------------------------------------
// CO2070 Computer Architecture - Lab 05
// Top-level CPU for the Simple 8-bit Processor with Data Cache
//
// Lab 06 connects the byte-addressed data-memory interface to a data cache. The
// CPU still sees the same READ/WRITE/ADDRESS/WRITEDATA/READDATA/BUSYWAIT
// signals as in Lab 05, but the cache now resolves hits quickly and stalls only
// on misses.
//      lwd RD RS   : RD = memory[register RS]
//      lwi RD IMM  : RD = memory[IMM]
//      swd RT RS   : memory[register RS] = RT
//      swi RT IMM  : memory[IMM] = RT
//
// While BUSYWAIT is high, the CPU holds the PC stable. For load instructions,
// the register-file write is held until BUSYWAIT becomes low, so the loaded byte
// is written only after the cache has produced valid READDATA.
// -----------------------------------------------------------------------------

module cpu(
    PC,
    INSTRUCTION,
    CLK,
    RESET,
    MEM_READ,
    MEM_WRITE,
    MEM_ADDRESS,
    MEM_WRITEDATA,
    MEM_READDATA,
    MEM_BUSYWAIT,
    INST_BUSYWAIT
);

    // -------------------------------------------------------------------------
    // Port declarations
    // -------------------------------------------------------------------------
    output reg [31:0] PC;          // Byte address of the current instruction.
    input      [31:0] INSTRUCTION; // 32-bit instruction from instruction memory.
    input             CLK;
    input             RESET;

    output            MEM_READ;      // Request a data-memory read.
    output            MEM_WRITE;     // Request a data-memory write.
    output     [7:0]  MEM_ADDRESS;   // Byte address for data memory.
    output     [7:0]  MEM_WRITEDATA; // Byte written to data memory.
    input      [7:0]  MEM_READDATA;  // Byte read from data memory.
    input             MEM_BUSYWAIT;  // Data-memory stall signal.
    input             INST_BUSYWAIT; // Instruction-cache stall signal.

    // -------------------------------------------------------------------------
    // OP-CODE definitions. These values match programmer/CO2070Assembler.c.
    // -------------------------------------------------------------------------
    parameter OP_LOADI = 8'b00000000;
    parameter OP_MOV   = 8'b00000001;
    parameter OP_ADD   = 8'b00000010;
    parameter OP_SUB   = 8'b00000011;
    parameter OP_AND   = 8'b00000100;
    parameter OP_OR    = 8'b00000101;
    parameter OP_J     = 8'b00000110;
    parameter OP_BEQ   = 8'b00000111;
    parameter OP_LWD   = 8'b00001000;
    parameter OP_LWI   = 8'b00001001;
    parameter OP_SWD   = 8'b00001010;
    parameter OP_SWI   = 8'b00001011;

    // -------------------------------------------------------------------------
    // ALU SELECT / ALUOP definitions. These values match the ALU module.
    // -------------------------------------------------------------------------
    parameter ALU_FORWARD = 3'b000;
    parameter ALU_ADD     = 3'b001;
    parameter ALU_AND     = 3'b010;
    parameter ALU_OR      = 3'b011;

    // -------------------------------------------------------------------------
    // Instruction field extraction.
    //      [31:24] : opcode
    //      [23:16] : RD for most instructions, signed offset for j/beq
    //      [15:8]  : RT
    //      [7:0]   : RS or immediate value
    // -------------------------------------------------------------------------
    wire [7:0] OPCODE;
    wire [7:0] RD_FIELD;
    wire [7:0] RT_FIELD;
    wire [7:0] RS_IMM_FIELD;

    assign OPCODE       = INSTRUCTION[31:24];
    assign RD_FIELD     = INSTRUCTION[23:16];
    assign RT_FIELD     = INSTRUCTION[15:8];
    assign RS_IMM_FIELD = INSTRUCTION[7:0];

    wire [2:0] RD_ADDR;
    wire [2:0] RT_ADDR;
    wire [2:0] RS_ADDR;

    assign RD_ADDR = RD_FIELD[2:0];
    assign RT_ADDR = RT_FIELD[2:0];
    assign RS_ADDR = RS_IMM_FIELD[2:0];

    wire [7:0] IMMEDIATE;
    assign IMMEDIATE = RS_IMM_FIELD;

    // -------------------------------------------------------------------------
    // Control signals generated by instruction decode.
    // -------------------------------------------------------------------------
    reg [2:0] READREG1;
    reg [2:0] READREG2;
    reg [2:0] WRITEREG;
    reg       WRITEENABLE;
    reg [2:0] ALUOP;

    reg       USE_IMMEDIATE; // Selects immediate value for ALU DATA2.
    reg       USE_2SCOMP;    // Selects two's complement of REGOUT2 for sub/beq.
    reg       JUMP;
    reg       BRANCH;

    reg       DATA_MEM_READ;
    reg       DATA_MEM_WRITE;
    reg       MEM_TO_REG;    // Selects MEM_READDATA as register-file write data.

    // -------------------------------------------------------------------------
    // Internal datapath wires.
    // -------------------------------------------------------------------------
    wire [7:0] REGOUT1;
    wire [7:0] REGOUT2;

    wire [7:0] ALU_DATA1;
    wire [7:0] ALU_DATA2;
    wire [7:0] ALURESULT;
    wire       ZERO;
    wire [7:0] REG_WRITE_DATA;
    wire       REG_WRITE_ENABLE;

    // -------------------------------------------------------------------------
    // Two's complement block. Used by sub and beq.
    // Artificial delay = #1.
    // -------------------------------------------------------------------------
    wire [7:0] NEG_REGOUT2;
    assign #1 NEG_REGOUT2 = ~REGOUT2 + 8'b00000001;

    // -------------------------------------------------------------------------
    // Control Unit / Instruction Decode.
    // Artificial decode delay = #1.
    // -------------------------------------------------------------------------
    always @(*) begin
        #1;

        READREG1       = 3'b000;
        READREG2       = 3'b000;
        WRITEREG       = RD_ADDR;
        WRITEENABLE    = 1'b0;
        ALUOP          = ALU_FORWARD;
        USE_IMMEDIATE  = 1'b0;
        USE_2SCOMP     = 1'b0;
        JUMP           = 1'b0;
        BRANCH         = 1'b0;
        DATA_MEM_READ  = 1'b0;
        DATA_MEM_WRITE = 1'b0;
        MEM_TO_REG     = 1'b0;

        case (OPCODE)
            OP_LOADI: begin
                // loadi RD IMM : RD = IMM
                WRITEREG      = RD_ADDR;
                WRITEENABLE   = 1'b1;
                ALUOP         = ALU_FORWARD;
                USE_IMMEDIATE = 1'b1;
            end

            OP_MOV: begin
                // mov RD RS : RD = RS
                READREG2    = RS_ADDR;
                WRITEREG    = RD_ADDR;
                WRITEENABLE = 1'b1;
                ALUOP       = ALU_FORWARD;
            end

            OP_ADD: begin
                // add RD RT RS : RD = RT + RS
                READREG1    = RT_ADDR;
                READREG2    = RS_ADDR;
                WRITEREG    = RD_ADDR;
                WRITEENABLE = 1'b1;
                ALUOP       = ALU_ADD;
            end

            OP_SUB: begin
                // sub RD RT RS : RD = RT - RS
                READREG1    = RT_ADDR;
                READREG2    = RS_ADDR;
                WRITEREG    = RD_ADDR;
                WRITEENABLE = 1'b1;
                ALUOP       = ALU_ADD;
                USE_2SCOMP  = 1'b1;
            end

            OP_AND: begin
                // and RD RT RS : RD = RT & RS
                READREG1    = RT_ADDR;
                READREG2    = RS_ADDR;
                WRITEREG    = RD_ADDR;
                WRITEENABLE = 1'b1;
                ALUOP       = ALU_AND;
            end

            OP_OR: begin
                // or RD RT RS : RD = RT | RS
                READREG1    = RT_ADDR;
                READREG2    = RS_ADDR;
                WRITEREG    = RD_ADDR;
                WRITEENABLE = 1'b1;
                ALUOP       = ALU_OR;
            end

            OP_J: begin
                // j OFFSET : PC = PC + 4 + sign_extend(OFFSET) * 4
                JUMP = 1'b1;
            end

            OP_BEQ: begin
                // beq OFFSET RT RS : branch when RT == RS
                READREG1   = RT_ADDR;
                READREG2   = RS_ADDR;
                ALUOP      = ALU_ADD;
                USE_2SCOMP = 1'b1;
                BRANCH     = 1'b1;
            end

            OP_LWD: begin
                // lwd RD RS : RD = memory[register RS]
                READREG2      = RS_ADDR;
                WRITEREG      = RD_ADDR;
                WRITEENABLE   = 1'b1;
                ALUOP         = ALU_FORWARD;
                DATA_MEM_READ = 1'b1;
                MEM_TO_REG    = 1'b1;
            end

            OP_LWI: begin
                // lwi RD IMM : RD = memory[IMM]
                WRITEREG      = RD_ADDR;
                WRITEENABLE   = 1'b1;
                ALUOP         = ALU_FORWARD;
                USE_IMMEDIATE = 1'b1;
                DATA_MEM_READ = 1'b1;
                MEM_TO_REG    = 1'b1;
            end

            OP_SWD: begin
                // swd RT RS : memory[register RS] = RT
                READREG1       = RT_ADDR;
                READREG2       = RS_ADDR;
                ALUOP          = ALU_FORWARD;
                DATA_MEM_WRITE = 1'b1;
            end

            OP_SWI: begin
                // swi RT IMM : memory[IMM] = RT
                READREG1       = RT_ADDR;
                ALUOP          = ALU_FORWARD;
                USE_IMMEDIATE  = 1'b1;
                DATA_MEM_WRITE = 1'b1;
            end

            default: begin
                // Unsupported opcodes are treated as no-ops.
            end
        endcase
    end

    // -------------------------------------------------------------------------
    // Register File instance.
    // Load instructions write only when the cache has completed the access.
    // -------------------------------------------------------------------------
    assign REG_WRITE_DATA   = (MEM_TO_REG == 1'b1) ? MEM_READDATA : ALURESULT;
    // A fetched instruction may write a register only when both memory paths
    // have completed. This prevents an old instruction from executing again
    // while an instruction-cache miss holds the PC constant.
    assign REG_WRITE_ENABLE = WRITEENABLE &
                              (MEM_BUSYWAIT == 1'b0) &
                              (INST_BUSYWAIT == 1'b0);

    reg_file my_reg_file(
        REG_WRITE_DATA,
        REGOUT1,
        REGOUT2,
        WRITEREG,
        READREG1,
        READREG2,
        REG_WRITE_ENABLE,
        CLK,
        RESET
    );

    // -------------------------------------------------------------------------
    // ALU input MUXes.
    // Memory instructions use the FORWARD operation to pass either a register
    // address or an immediate address to the data-memory ADDRESS port.
    // -------------------------------------------------------------------------
    assign ALU_DATA1 = REGOUT1;
    assign ALU_DATA2 = (USE_IMMEDIATE == 1'b1) ? IMMEDIATE :
                       (USE_2SCOMP    == 1'b1) ? NEG_REGOUT2 :
                                                  REGOUT2;

    alu my_alu(
        ALU_DATA1,
        ALU_DATA2,
        ALURESULT,
        ZERO,
        ALUOP
    );

    // -------------------------------------------------------------------------
    // Data-memory interface.
    // The CPU keeps these signals stable because the PC is held while the cache
    // asserts MEM_BUSYWAIT.
    // -------------------------------------------------------------------------
    assign MEM_READ      = DATA_MEM_READ;
    assign MEM_WRITE     = DATA_MEM_WRITE;
    assign MEM_ADDRESS   = ALURESULT;
    assign MEM_WRITEDATA = REGOUT1;

    // -------------------------------------------------------------------------
    // PC + 4 and branch/jump target calculation.
    // -------------------------------------------------------------------------
    wire [31:0] PC_PLUS4;
    assign #1 PC_PLUS4 = PC + 32'd4;

    wire signed [31:0] SIGN_EXT_OFFSET;
    wire signed [31:0] OFFSET_SHIFTED;

    assign SIGN_EXT_OFFSET = {{24{RD_FIELD[7]}}, RD_FIELD};
    assign OFFSET_SHIFTED  = SIGN_EXT_OFFSET <<< 2;

    wire [31:0] BRANCH_TARGET;
    assign #2 BRANCH_TARGET = PC_PLUS4 + OFFSET_SHIFTED;

    wire TAKE_BRANCH;
    assign TAKE_BRANCH = JUMP | (BRANCH & ZERO);

    // -------------------------------------------------------------------------
    // Program Counter update logic.
    // RESET forces PC to zero. BUSYWAIT stalls the CPU only on cache misses.
    // Artificial PC register update delay = #1.
    // -------------------------------------------------------------------------
    always @(posedge CLK) begin
        if (RESET == 1'b1) begin
            #1 PC <= 32'b0;
        end
        else if ((MEM_BUSYWAIT == 1'b1) || (INST_BUSYWAIT == 1'b1)) begin
            #1 PC <= PC;
        end
        else begin
            #1 PC <= (TAKE_BRANCH == 1'b1) ? BRANCH_TARGET : PC_PLUS4;
        end
    end

endmodule
