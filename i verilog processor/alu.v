`timescale 1ns/100ps
// -----------------------------------------------------------------------------
// CO2070 Computer Architecture - Lab 04
// 8-bit ALU for the Simple Processor
//
// Lab 04 change:
//   The ALU now has an additional ZERO output. ZERO becomes 1 when the selected
//   ALU RESULT is 8'b00000000. The CPU uses this signal for the beq instruction:
//
//        beq offset RT RS
//
//   The CPU subtracts RS from RT using two's complement. If the subtraction
//   result is zero, the two registers are equal and the branch can be taken.
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
// FORWARD unit
// Used by loadi and mov instructions.
// DATA2 is directly forwarded to RESULT.
// Artificial functional-unit delay = #1.
// -----------------------------------------------------------------------------
module forward_unit(DATA2, RESULT);
    input  [7:0] DATA2;
    output [7:0] RESULT;

    assign #1 RESULT = DATA2;
endmodule

// -----------------------------------------------------------------------------
// ADD unit
// Used by add, sub and beq.
// For sub/beq, the CPU sends the two's complement of DATA2 to this unit.
// Artificial functional-unit delay = #2.
// -----------------------------------------------------------------------------
module add_unit(DATA1, DATA2, RESULT);
    input  [7:0] DATA1;
    input  [7:0] DATA2;
    output [7:0] RESULT;

    assign #2 RESULT = DATA1 + DATA2;
endmodule

// -----------------------------------------------------------------------------
// AND unit
// Used by and instruction.
// Artificial functional-unit delay = #1.
// -----------------------------------------------------------------------------
module and_unit(DATA1, DATA2, RESULT);
    input  [7:0] DATA1;
    input  [7:0] DATA2;
    output [7:0] RESULT;

    assign #1 RESULT = DATA1 & DATA2;
endmodule

// -----------------------------------------------------------------------------
// OR unit
// Used by or instruction.
// Artificial functional-unit delay = #1.
// -----------------------------------------------------------------------------
module or_unit(DATA1, DATA2, RESULT);
    input  [7:0] DATA1;
    input  [7:0] DATA2;
    output [7:0] RESULT;

    assign #1 RESULT = DATA1 | DATA2;
endmodule

// -----------------------------------------------------------------------------
// Main ALU module
// Interface used in Lab 04:
//      module alu(DATA1, DATA2, RESULT, ZERO, SELECT)
//
// DATA1, DATA2 : 8-bit ALU operands
// SELECT       : 3-bit ALU operation select signal generated by the CPU control
// RESULT       : selected ALU result
// ZERO         : 1 when RESULT == 0, otherwise 0
// -----------------------------------------------------------------------------
module alu(DATA1, DATA2, RESULT, ZERO, SELECT);

    input  [7:0] DATA1;
    input  [7:0] DATA2;
    input  [2:0] SELECT;

    output reg [7:0] RESULT;
    output           ZERO;

    // Outputs from the separate functional units.
    wire [7:0] forward_result;
    wire [7:0] add_result;
    wire [7:0] and_result;
    wire [7:0] or_result;

    // Instantiate the functional units.
    forward_unit FU (DATA2,       forward_result);
    add_unit     AU (DATA1, DATA2, add_result);
    and_unit     ANU(DATA1, DATA2, and_result);
    or_unit      ORU(DATA1, DATA2, or_result);

    // This always block works as the ALU output multiplexer.
    // MUX delay is assumed to be negligible according to the lab sheet.
    always @(*) begin
        case (SELECT)
            3'b000: RESULT = forward_result;  // FORWARD: DATA2 -> RESULT
            3'b001: RESULT = add_result;      // ADD:     DATA1 + DATA2
            3'b010: RESULT = and_result;      // AND:     DATA1 & DATA2
            3'b011: RESULT = or_result;       // OR:      DATA1 | DATA2
            default: RESULT = 8'b00000000;    // Reserved ALUOP values
        endcase
    end

    // ZERO output for branch comparison.
    // For beq, the CPU performs RT - RS. If RESULT is zero, RT == RS.
    assign ZERO = (RESULT == 8'b00000000) ? 1'b1 : 1'b0;

endmodule
